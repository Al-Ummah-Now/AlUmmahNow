/**
 * Builds the server's prayer city catalogue (wiki Epic 21 §3, E21-D3) from GeoNames
 * `cities15000.txt` (CC BY 4.0, https://download.geonames.org/export/dump/cities15000.zip).
 *
 *   node --experimental-strip-types scripts/build-prayer-cities.ts <path/to/cities15000.txt>
 *
 * Writes src/lib/prayer/cities.data.ts: one line per city, "id\tlat\tlon\tcountry\ttimeZone\tname",
 * coordinates rounded to 4 decimals (about 11 m). Only public city coordinates; never a user's.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const source = process.argv[2];
if (!source) {
	process.stderr.write('usage: build-prayer-cities.ts <cities15000.txt>\n');
	process.exit(2);
}

const rows: string[] = [];
for (const line of readFileSync(source, 'utf8').split('\n')) {
	if (!line) continue;
	const f = line.split('\t');
	// 0 id, 2 asciiname, 4 lat, 5 lon, 8 country, 17 time zone
	const [id, ascii, lat, lon, cc, tz] = [f[0], f[2], Number(f[4]), Number(f[5]), f[8], f[17]];
	if (!/^[1-9][0-9]*$/.test(id) || !Number.isFinite(lat) || !Number.isFinite(lon) || !/^[A-Z]{2}$/.test(cc) || !tz) continue;
	const name = ascii.replace(/[\t\n\\`$]/g, ' ').trim();
	rows.push(`${id}\t${lat.toFixed(4)}\t${lon.toFixed(4)}\t${cc}\t${tz}\t${name}`);
}
rows.sort((a, b) => Number(a.split('\t')[0]) - Number(b.split('\t')[0]));
const out = join(import.meta.dirname, '..', 'src', 'lib', 'prayer', 'cities.data.ts');
writeFileSync(
	out,
	`// GENERATED by scripts/build-prayer-cities.ts from GeoNames cities15000 (CC BY 4.0, https://www.geonames.org/). Do not edit by hand.\n` +
		`// ${rows.length} cities: id, latitude, longitude, country, time zone, name.\n` +
		`export const PRAYER_CITIES_TSV = \`\n${rows.join('\n')}\n\`;\n`,
);
process.stdout.write(`${rows.length} cities -> ${out}\n`);
