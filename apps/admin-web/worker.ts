/**
 * Worker entry (wrangler `main`): the OpenNext worker, plus the public host
 * kept across a skew-protection hop (src/lib/version-skew/skew-host.ts).
 * Build first: `opennextjs-cloudflare build` writes .open-next/worker.js.
 *
 * Each page/API request emits one summary line (logging policy,
 * docs/operations/logging.md): info at stage and below, warn when slow, error
 * on a 5xx or a throw. Static assets are not summarised.
 */
// .open-next/worker.js exists only after a build, so the import may or may not resolve for tsc
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore: generated by the OpenNext build
import openNext from './.open-next/worker.js';
import { configureLogging, type LoggingEnv } from '@al-ummah/logger';
import { withPublicHost } from './src/lib/version-skew/skew-host';
import { logger } from './src/lib/logger-server';
import { asServiceUnavailable } from './src/lib/seo/unavailable';
import { asGoneIfPurged } from './src/lib/seo/gone';
import { rootLocaleRedirect } from './src/lib/seo/root-locale';

interface Handler {
  fetch(request: Request, env: unknown, ctx: unknown): Promise<Response>;
}

/** Build assets, images and other files: no summary line. */
const STATIC_PATH = /^\/(_next\/(static|image)|favicon|robots\.txt|sitemap|manifest|sw\.js|icons?\/|images?\/|fonts?\/)|\.(js|css|map|png|jpe?g|gif|svg|webp|avif|ico|woff2?|ttf|txt|xml|json)$/;

const worker: Handler = {
  async fetch(request, env, ctx) {
    // `/` → `/en` or `/ar` before Next runs (no middleware, session refresh or render): the cheapest hop
    const root = rootLocaleRedirect(request);
    if (root) return root;
    configureLogging(env as LoggingEnv);
    const startedAt = Date.now();
    const route = new URL(request.url).pathname;
    const summarise = !STATIC_PATH.test(route);
    const base = { method: request.method, route, ray: request.headers.get('cf-ray') || undefined };
    try {
      const response = await (openNext as Handler).fetch(withPublicHost(request), env, ctx);
      if (summarise) logger.request({ ...base, status: response.status, durationMs: Date.now() - startedAt });
      return asGoneIfPurged(request, asServiceUnavailable(request, response), env);
    } catch (error) {
      logger.request({ ...base, status: 500, durationMs: Date.now() - startedAt, error });
      throw error;
    }
  },
};

export default worker;
