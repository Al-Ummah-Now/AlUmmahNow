/** The SVG markup for an icon: 24px grid, stroked in currentColor, hidden from assistive technology. */
export function iconSvg(name: IconName): string {
  return `<svg class="vjs-svg-icon-fanous" data-icon="${name}" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${ICONS[name]}</svg>`;
}

/**
 * Puts SVG icons inside a Video.js control's .vjs-icon-placeholder, replacing any earlier ones.
 * A control with several states (play, pause, replay) gets one icon per state; CSS shows one.
 * The markup is the constant ICONS table, never user input.
 */
export function setControlIcons(controlEl: Element | null | undefined, ...names: IconName[]): void {
  const holder = controlEl?.querySelector('.vjs-icon-placeholder') ?? (controlEl?.classList.contains('vjs-big-play-button') ? controlEl : null);
  if (!holder) return;
  const have = Array.from(holder.querySelectorAll('svg.vjs-svg-icon-fanous')).map((s) => s.getAttribute('data-icon'));
  if (have.join() === names.join()) return;
  holder.querySelectorAll('svg.vjs-svg-icon-fanous').forEach((s) => s.remove());
  holder.insertAdjacentHTML('afterbegin', names.map(iconSvg).join(''));
}
