'use client';
import { logger } from '@/lib/logger-client';
import { FitImage } from '@/components/VideoThumbnail/FitImage';

import React, { useState, useRef } from 'react';
import { Upload, Check } from 'lucide-react';
import { useLanguage } from '@/hooks/useLanguage';
import { uploadVideoThumbnail, validateThumbnailFile } from '@/lib/api/video-thumbnail-client';

interface ThumbnailSelectorProps {
  videoId: string;
  currentThumbnailUrl: string;
  /**
   * The video's HLS URL (https://vz-xxx.b-cdn.net/{videoId}/playlist.m3u8).
   * Bunny serves the frames it generates during encoding next to it.
   */
  playUrl?: string;
  channelId: string;
  onThumbnailChange: (thumbnailUrl: string) => void;
  className?: string;
}

/** Bunny Stream generates thumbnail_1.jpg … thumbnail_N.jpg while encoding */
const AUTO_THUMBNAIL_COUNT = 5;

/** Directory holding the video's Bunny files, derived from its HLS URL */
export function getVideoCdnDirectory(playUrl?: string): string | null {
  if (!playUrl) return null;
  try {
    const url = new URL(playUrl);
    const dir = url.pathname.replace(/\/[^/]*$/, '');
    return dir ? `${url.origin}${dir}` : null;
  } catch {
    return null;
  }
}

export default function ThumbnailSelector({
  videoId,
  currentThumbnailUrl,
  playUrl,
  channelId,
  onThumbnailChange,
  className = '',
}: ThumbnailSelectorProps) {
  const { t } = useLanguage();
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [selectedThumbnail, setSelectedThumbnail] = useState(currentThumbnailUrl);
  const [customThumbnail, setCustomThumbnail] = useState<string | null>(null);
  const [isUploading, setIsUploading] = useState(false);
  const [uploadError, setUploadError] = useState<string | null>(null);
  // Frames that failed to load (short videos get fewer; unencoded videos none)
  const [missingFrames, setMissingFrames] = useState<Set<string>>(new Set());

  const cdnDirectory = getVideoCdnDirectory(playUrl);
  const autoGeneratedThumbnails = cdnDirectory
    ? Array.from({ length: AUTO_THUMBNAIL_COUNT }, (_, i) => `${cdnDirectory}/thumbnail_${i + 1}.jpg`)
    : [];
  const visibleAutoThumbnails = autoGeneratedThumbnails.filter((url) => !missingFrames.has(url));

  const handleThumbnailSelect = (thumbnailUrl: string) => {
    setSelectedThumbnail(thumbnailUrl);
    onThumbnailChange(thumbnailUrl);
  };

  const handleFrameError = (url: string) => {
    setMissingFrames((prev) => new Set(prev).add(url));
  };

  const handleFileChange = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    // Allow re-selecting the same file after an error
    e.target.value = '';

    const validationError = validateThumbnailFile(file);
    if (validationError) {
      setUploadError(validationError === 'invalid_type' ? t.video.thumbnailInvalidType ?? null : t.video.thumbnailTooLarge ?? null);
      return;
    }

    setUploadError(null);
    setIsUploading(true);

    try {
      // Preview the image locally
      const reader = new FileReader();
      reader.onload = (event) => {
        setCustomThumbnail(event.target?.result as string);
      };
      reader.readAsDataURL(file);

      // Upload directly to the API (owner-only endpoint, stores in image CDN)
      const result = await uploadVideoThumbnail(videoId, file, channelId);

      if (result.success && result.thumbnailUrl) {
        const uploadedUrl = result.thumbnailUrl;
        setCustomThumbnail(uploadedUrl);
        setSelectedThumbnail(uploadedUrl);
        onThumbnailChange(uploadedUrl);
      } else {
        setCustomThumbnail(null);
        setUploadError(result.error || t.video.thumbnailUploadFailed || null);
      }
    } catch (error) {
      logger.error('[ThumbnailSelector] Error uploading thumbnail', { videoId, error });
      setCustomThumbnail(null);
      setUploadError(t.video.thumbnailUploadFailed ?? null);
    } finally {
      setIsUploading(false);
    }
  };

  const handleUploadClick = () => {
    fileInputRef.current?.click();
  };

  const selectionLabel = (() => {
    if (selectedThumbnail === currentThumbnailUrl) return t.video.thumbnailCurrentDefault;
    if (selectedThumbnail === customThumbnail) return t.video.customThumbnail;
    return `${t.video.autoGeneratedThumbnails} #${autoGeneratedThumbnails.indexOf(selectedThumbnail) + 1}`;
  })();

  return (
    <div className={`space-y-4 ${className}`} data-testid="thumbnail-selector">
      <div>
        <h3 className="text-lg font-semibold mb-2 dark:text-white">
          {t.video.thumbnailSelector}
        </h3>
        <p className="text-sm text-gray-600 dark:text-gray-400 mb-4">
          {t.video.thumbnailRequirements}
        </p>
      </div>

      {/* Auto-generated Thumbnails */}
      {visibleAutoThumbnails.length > 0 && (
        <div>
          <h4 id={`auto-thumbnails-${videoId}`} className="text-sm font-medium mb-2 dark:text-white">
            {t.video.autoGeneratedThumbnails}
          </h4>
          <div
            role="radiogroup"
            aria-labelledby={`auto-thumbnails-${videoId}`}
            className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-5 gap-3"
          >
            {autoGeneratedThumbnails.map((url, index) =>
              missingFrames.has(url) ? null : (
                <button
                  key={url}
                  type="button"
                  role="radio"
                  aria-checked={selectedThumbnail === url}
                  aria-label={`${t.video.autoGeneratedThumbnails} ${index + 1}`}
                  data-testid="thumbnail-auto-option"
                  onClick={() => handleThumbnailSelect(url)}
                  className={`relative aspect-video rounded-lg overflow-hidden border-2 transition-all focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 ${
                    selectedThumbnail === url
                      ? 'border-blue-500 ring-2 ring-blue-200 dark:ring-blue-800'
                      : 'border-gray-300 dark:border-gray-600 hover:border-blue-300 dark:hover:border-blue-700'
                  }`}
                >
                  <FitImage
                    src={url}
                    alt={`${t.video.autoGeneratedThumbnails} ${index + 1}`}
                    sizes="(max-width: 768px) 50vw, 20vw"
                    onError={() => handleFrameError(url)}
                  />
                  {selectedThumbnail === url && (
                    <div className="absolute inset-0 bg-blue-500/20 flex items-center justify-center">
                      <div className="bg-blue-500 rounded-full p-1">
                        <Check size={16} className="text-white" />
                      </div>
                    </div>
                  )}
                </button>
              )
            )}
          </div>
        </div>
      )}

      {/* Custom Thumbnail Upload */}
      <div>
        <h4 className="text-sm font-medium mb-2 dark:text-white">
          {t.video.customThumbnail}
        </h4>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {/* Custom thumbnail preview */}
          {customThumbnail && (
            <button
              type="button"
              aria-pressed={selectedThumbnail === customThumbnail}
              aria-label={t.video.customThumbnail}
              data-testid="thumbnail-custom-option"
              onClick={() => handleThumbnailSelect(customThumbnail)}
              className={`relative aspect-video rounded-lg overflow-hidden border-2 transition-all ${
                selectedThumbnail === customThumbnail
                  ? 'border-blue-500 ring-2 ring-blue-200 dark:ring-blue-800'
                  : 'border-gray-300 dark:border-gray-600 hover:border-blue-300 dark:hover:border-blue-700'
              }`}
            >
              <FitImage
                src={customThumbnail}
                alt={t.video.customThumbnail ?? ''}
                sizes="(max-width: 768px) 100vw, 50vw"
              />
              {selectedThumbnail === customThumbnail && (
                <div className="absolute inset-0 bg-blue-500/20 flex items-center justify-center">
                  <div className="bg-blue-500 rounded-full p-1">
                    <Check size={16} className="text-white" />
                  </div>
                </div>
              )}
            </button>
          )}

          {/* Upload button */}
          <button
            type="button"
            onClick={handleUploadClick}
            disabled={isUploading}
            aria-busy={isUploading}
            data-testid="thumbnail-upload-button"
            className="relative aspect-video rounded-lg border-2 border-dashed border-gray-300 dark:border-gray-600 hover:border-blue-400 dark:hover:border-blue-600 transition-colors flex flex-col items-center justify-center gap-2 text-gray-600 dark:text-gray-400 hover:text-blue-500 dark:hover:text-blue-400 disabled:opacity-50 disabled:cursor-not-allowed"
          >
            <Upload size={32} />
            <span className="text-sm font-medium">
              {isUploading ? t.common.loading : t.video.uploadThumbnail}
            </span>
            <span className="text-xs px-2 text-center">
              {t.video.dragDropThumbnail}
            </span>
          </button>
        </div>

        <input
          ref={fileInputRef}
          type="file"
          accept="image/jpeg,image/png,image/webp"
          onChange={handleFileChange}
          data-testid="thumbnail-file-input"
          aria-label={t.video.uploadThumbnail}
          className="hidden"
        />

        {uploadError && (
          <p role="alert" data-testid="thumbnail-upload-error" className="text-sm text-red-500 mt-2">{uploadError}</p>
        )}
      </div>

      {/* Current Selection (announced to screen readers when it changes) */}
      <div className="pt-2 border-t dark:border-gray-700">
        <p className="text-sm text-gray-600 dark:text-gray-400" aria-live="polite" data-testid="thumbnail-current-selection">
          {t.video.currentThumbnail}:{' '}
          <span className="text-gray-900 dark:text-white font-medium">
            {selectionLabel}
          </span>
        </p>
      </div>
    </div>
  );
}
