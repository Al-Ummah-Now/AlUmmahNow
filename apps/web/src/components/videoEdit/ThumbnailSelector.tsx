'use client';
import { logger } from '@/lib/logger-client';

import React, { useState, useRef } from 'react';
import Image from 'next/image';
import { Upload, Check } from 'lucide-react';
import { useLanguage } from '@/hooks/useLanguage';
import { uploadVideoThumbnail } from '@/lib/api/videos';

interface ThumbnailSelectorProps {
  videoId: string;
  currentThumbnailUrl: string;
  cdnHostname?: string;
  channelId: string;
  onThumbnailChange: (thumbnailUrl: string) => void;
  className?: string;
}

export default function ThumbnailSelector({
  videoId,
  currentThumbnailUrl,
  cdnHostname,
  channelId,
  onThumbnailChange,
  className = '',
}: ThumbnailSelectorProps) {
  const { t } = useLanguage();
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [selectedThumbnail, setSelectedThumbnail] = useState(currentThumbnailUrl);
  const [customThumbnail, setCustomThumbnail] = useState<string | null>(null);
  const [isUploading, setIsUploading] = useState(false);
  const [uploadError, setUploadError] = useState<string | null>(null);

  // Generate auto-generated thumbnail URLs from Bunny.net
  // Bunny.net generates thumbnails at 0%, 25%, 50%, 75%, 100% of video duration
  const autoGeneratedThumbnails = cdnHostname
    ? [
        `https://vz-${cdnHostname}.b-cdn.net/${videoId}/thumbnail_0.jpg`,
        `https://vz-${cdnHostname}.b-cdn.net/${videoId}/thumbnail_25.jpg`,
        `https://vz-${cdnHostname}.b-cdn.net/${videoId}/thumbnail_50.jpg`,
        `https://vz-${cdnHostname}.b-cdn.net/${videoId}/thumbnail_75.jpg`,
        `https://vz-${cdnHostname}.b-cdn.net/${videoId}/thumbnail_100.jpg`,
      ]
    : [];

  const handleThumbnailSelect = (thumbnailUrl: string) => {
    setSelectedThumbnail(thumbnailUrl);
    onThumbnailChange(thumbnailUrl);
  };

  const handleFileChange = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    // Validate file type
    if (!file.type.startsWith('image/')) {
      setUploadError('Please select an image file');
      return;
    }

    // Validate file size (max 2MB)
    if (file.size > 2 * 1024 * 1024) {
      setUploadError('Image must be less than 2MB');
      return;
    }

    setUploadError(null);
    setIsUploading(true);

    try {
      // Preview the image locally
      const reader = new FileReader();
      reader.onload = (event) => {
        setCustomThumbnail(event.target?.result as string);
      };
      reader.readAsDataURL(file);

      // Upload to API
      const result = await uploadVideoThumbnail(videoId, file, { channelId });

      if (result?.data?.thumbnailUrl) {
        const uploadedUrl = result.data.thumbnailUrl;
        setCustomThumbnail(uploadedUrl ?? null);
        setSelectedThumbnail(uploadedUrl ?? null);
        onThumbnailChange(uploadedUrl);
      } else {
        setUploadError(t.video.thumbnailUploadFailed ?? 'Failed to upload thumbnail');
      }
    } catch (error) {
      logger.error('Error uploading thumbnail:', error);
      setUploadError(t.video.thumbnailUploadFailed ?? 'Failed to upload thumbnail');
    } finally {
      setIsUploading(false);
    }
  };

  const handleUploadClick = () => {
    fileInputRef.current?.click();
  };

  return (
    <div className={`space-y-4 ${className}`}>
      <div>
        <h3 className="text-lg font-semibold mb-2 dark:text-white">
          {t.video.thumbnailSelector}
        </h3>
        <p className="text-sm text-gray-600 dark:text-gray-400 mb-4">
          {t.video.thumbnailRequirements}
        </p>
      </div>

      {/* Auto-generated Thumbnails */}
      {autoGeneratedThumbnails.length > 0 && (
        <div>
          <h4 className="text-sm font-medium mb-2 dark:text-white">
            {t.video.autoGeneratedThumbnails}
          </h4>
          <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-5 gap-3">
            {autoGeneratedThumbnails.map((url, index) => (
              <button
                key={url}
                onClick={() => handleThumbnailSelect(url)}
                className={`relative aspect-video rounded-lg overflow-hidden border-2 transition-all ${
                  selectedThumbnail === url
                    ? 'border-blue-500 ring-2 ring-blue-200 dark:ring-blue-800'
                    : 'border-gray-300 dark:border-gray-600 hover:border-blue-300 dark:hover:border-blue-700'
                }`}
              >
                <Image
                  src={url}
                  alt={`Thumbnail ${index + 1}`}
                  fill
                  className="object-cover"
                  sizes="(max-width: 768px) 50vw, 20vw"
                />
                {selectedThumbnail === url && (
                  <div className="absolute inset-0 bg-blue-500/20 flex items-center justify-center">
                    <div className="bg-blue-500 rounded-full p-1">
                      <Check size={16} className="text-white" />
                    </div>
                  </div>
                )}
              </button>
            ))}
          </div>
        </div>
      )}

      {/* Custom Thumbnail Upload */}
      <div>
        <h4 className="text-sm font-medium mb-2 dark:text-white">
          {t.video.customThumbnail}
        </h4>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {/* Custom thumbnail preview */}
          {customThumbnail && (
            <button
              onClick={() => handleThumbnailSelect(customThumbnail)}
              className={`relative aspect-video rounded-lg overflow-hidden border-2 transition-all ${
                selectedThumbnail === customThumbnail
                  ? 'border-blue-500 ring-2 ring-blue-200 dark:ring-blue-800'
                  : 'border-gray-300 dark:border-gray-600 hover:border-blue-300 dark:hover:border-blue-700'
              }`}
            >
              <Image
                src={customThumbnail}
                alt="Custom thumbnail"
                fill
                className="object-cover"
                sizes="(max-width: 768px) 100vw, 50vw"
              />
              {selectedThumbnail === customThumbnail && (
                <div className="absolute inset-0 bg-blue-500/20 flex items-center justify-center">
                  <div className="bg-blue-500 rounded-full p-1">
                    <Check size={16} className="text-white" />
                  </div>
                </div>
              )}
            </button>
          )}

          {/* Upload button */}
          <button
            onClick={handleUploadClick}
            disabled={isUploading}
            className="relative aspect-video rounded-lg border-2 border-dashed border-gray-300 dark:border-gray-600 hover:border-blue-400 dark:hover:border-blue-600 transition-colors flex flex-col items-center justify-center gap-2 text-gray-600 dark:text-gray-400 hover:text-blue-500 dark:hover:text-blue-400 disabled:opacity-50 disabled:cursor-not-allowed"
          >
            <Upload size={32} />
            <span className="text-sm font-medium">
              {isUploading ? t.common.loading : t.video.uploadThumbnail}
            </span>
            <span className="text-xs px-2 text-center">
              {t.video.dragDropThumbnail}
            </span>
          </button>
        </div>

        <input
          ref={fileInputRef}
          type="file"
          accept="image/*"
          onChange={handleFileChange}
          className="hidden"
        />

        {uploadError && (
          <p className="text-sm text-red-500 mt-2">{uploadError}</p>
        )}
      </div>

      {/* Current Selection */}
      {selectedThumbnail && (
        <div className="pt-2 border-t dark:border-gray-700">
          <p className="text-sm text-gray-600 dark:text-gray-400">
            {t.video.currentThumbnail}:{' '}
            <span className="text-gray-900 dark:text-white font-medium">
              {selectedThumbnail === currentThumbnailUrl
                ? 'Default'
                : selectedThumbnail === customThumbnail
                ? 'Custom'
                : `Auto-generated #${autoGeneratedThumbnails.indexOf(selectedThumbnail) + 1}`}
            </span>
          </p>
        </div>
      )}
    </div>
  );
}
