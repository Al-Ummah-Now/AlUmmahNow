/**
 * GoLiveWizard Types
 * Task 2.1: GoLiveForm Wizard Structure (4 Steps)
 *
 * Type definitions for the Go Live wizard component following the FSM pattern.
 */

/**
 * Wizard step numbers (1-indexed for user-facing display)
 */
export type WizardStep = 1 | 2 | 3 | 4;

/**
 * Step identifiers for type-safe step management
 */
export type StepId = 'details' | 'thumbnail' | 'rtmp' | 'review';

/**
 * Stream Details Data (Step 1)
 * Collected in the first step of the wizard
 */
export interface StreamDetailsData {
  /**
   * Stream title (required)
   */
  title: string;

  /**
   * Stream description (optional)
   */
  description?: string;

  /**
   * Stream category (required)
   */
  category: string;

  /**
   * Stream tags for discoverability (optional)
   */
  tags?: string[];

  /**
   * Scheduled start time (optional, for scheduled streams)
   */
  scheduledStartTime?: Date;

  /**
   * Whether to notify subscribers when going live (optional)
   */
  notifySubscribers?: boolean;
}

/**
 * Thumbnail Data (Step 2)
 * Thumbnail upload is optional but recommended
 */
export interface ThumbnailData {
  /**
   * Thumbnail URL (from Bunny.net upload)
   */
  thumbnailUrl?: string;

  /**
   * Thumbnail file object (before upload)
   */
  thumbnailFile?: File;

  /**
   * Upload progress (0-100)
   */
  uploadProgress?: number;

  /**
   * Whether thumbnail upload is in progress
   */
  isUploading?: boolean;
}

/**
 * RTMP Configuration (Step 3)
 * Generated stream key and server URL
 */
export interface RTMPConfig {
  /**
   * RTMP server URL
   */
  serverUrl: string;

  /**
   * Unique stream key (generated by backend)
   */
  streamKey: string;

  /**
   * Stream ID (from backend)
   */
  streamId: string;

  /**
   * Backup server URL (optional)
   */
  backupServerUrl?: string;
}

/**
 * Complete Stream Form Data
 * Combines all steps for final submission
 */
export type StreamFormData = StreamDetailsData & ThumbnailData & RTMPConfig;

/**
 * Wizard State Management
 * Uses FSM pattern for step transitions
 */
export interface GoLiveFormState {
  /**
   * Current step (1-4)
   */
  currentStep: WizardStep;

  /**
   * Step 1 data
   */
  streamDetails: StreamDetailsData | null;

  /**
   * Step 2 data
   */
  thumbnailData: ThumbnailData | null;

  /**
   * Step 3 data
   */
  rtmpConfig: RTMPConfig | null;

  /**
   * Stream ID (set after RTMP config is generated)
   */
  streamId: string | null;

  /**
   * Field-level validation errors
   */
  errors: Record<string, string>;

  /**
   * Loading state for async operations
   */
  isLoading: boolean;

  /**
   * Whether the form has unsaved changes
   */
  isDirty: boolean;

  /**
   * Whether draft recovery prompt was shown
   */
  draftRecoveryShown: boolean;
}

/**
 * Wizard Actions (FSM transitions)
 */
export type WizardAction =
  | { type: 'NEXT_STEP' }
  | { type: 'PREV_STEP' }
  | { type: 'GO_TO_STEP'; step: WizardStep }
  | { type: 'SET_DETAILS'; data: StreamDetailsData }
  | { type: 'SET_THUMBNAIL'; data: ThumbnailData }
  | { type: 'SET_RTMP'; data: RTMPConfig }
  | { type: 'SET_ERRORS'; errors: Record<string, string> }
  | { type: 'SET_LOADING'; isLoading: boolean }
  | { type: 'MARK_DIRTY' }
  | { type: 'MARK_DRAFT_SHOWN' }
  | { type: 'RESET' }
  | { type: 'RESTORE_DRAFT'; state: GoLiveFormState };

/**
 * Component Props
 */
export interface GoLiveWizardProps {
  /**
   * Channel ID for the stream
   */
  channelId: string;

  /**
   * User ID (from auth)
   */
  userId: string;

  /**
   * Callback when stream is successfully created
   * @param streamId - The created stream ID
   */
  onSuccess: (streamId: string) => void;

  /**
   * Callback when user cancels the wizard
   */
  onCancel: () => void;

  /**
   * Initial data for editing (optional)
   */
  initialData?: Partial<StreamFormData>;

  /**
   * Custom class name
   */
  className?: string;
}

/**
 * Step Component Props
 * Shared props for all step components
 */
export interface StepComponentProps {
  /**
   * Current form state
   */
  state: GoLiveFormState;

  /**
   * Dispatch function for state updates
   */
  dispatch: React.Dispatch<WizardAction>;

  /**
   * Callback to proceed to next step
   */
  onNext: () => void;

  /**
   * Callback to go back to previous step
   */
  onBack: () => void;

  /**
   * Whether the step is valid and can proceed
   */
  canProceed: boolean;
}

/**
 * Step Validation Result
 */
export interface StepValidationResult {
  /**
   * Whether the step is valid
   */
  valid: boolean;

  /**
   * Validation errors (field name -> error message)
   */
  errors?: Record<string, string>;

  /**
   * Validated data (if valid)
   */
  data?: any;
}

/**
 * Draft Recovery Data
 * Stored in sessionStorage
 */
export interface DraftRecoveryData {
  /**
   * Saved wizard state
   */
  state: GoLiveFormState;

  /**
   * Timestamp when draft was saved
   */
  savedAt: string;

  /**
   * Channel ID (for validation)
   */
  channelId: string;

  /**
   * User ID (for validation)
   */
  userId: string;
}

/**
 * Step Configuration
 * Metadata for each wizard step
 */
export interface StepConfig {
  /**
   * Step number (1-4)
   */
  step: WizardStep;

  /**
   * Step identifier
   */
  id: StepId;

  /**
   * Step title (translation key)
   */
  titleKey: string;

  /**
   * Step description (translation key, optional)
   */
  descriptionKey?: string;

  /**
   * Icon component (optional)
   */
  icon?: React.ComponentType<{ className?: string }>;

  /**
   * Whether the step is optional
   */
  optional?: boolean;
}

