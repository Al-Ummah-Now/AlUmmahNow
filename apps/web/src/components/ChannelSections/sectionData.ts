import type { Channel, ChannelSection, ChannelSectionType, LiveStream, VideoObject } from '@al-ummah/shared-types';
import { BRAND_LOGO_LARGE } from '@/components/brand/BrandLogo';

/**
 * Public-facing channel fields needed to render a channel tile.
 * Matches both the full Channel model and the API's populated section summaries.
 */
export type ChannelSummary = Pick<
  Channel,
  | 'id'
  | 'name'
  | 'nameLocalized'
  | 'description'
  | 'descriptionLocalized'
  | 'avatarUrl'
  | 'coverUrl'
  | 'isVerified'
  | 'subscribersCount'
  | 'videosCount'
> & Partial<Pick<Channel, 'handle' | 'userId' | 'isMain'>>;

/** Why an editor sees a section that visitors don't (API `emptyHint`) */
export type SectionEmptyHint = 'noContent' | 'consentMissing' | 'communityTabHidden' | 'loadFailed';

/** A community post as the API returns it for a Home tab section */
export interface SectionPostSummary {
  id: string;
  channelId: string;
  type: string;
  content?: string;
  image?: { url: string; width: number; height: number };
  videoId?: string;
  gifUrl?: string;
  poll?: { question: string; optionsCount: number };
  likes: number;
  comments: number;
  pinned: boolean;
  createdAt: string;
}

/** A playlist as the API returns it in section content (public fields, cover filled in) */
export interface SectionPlaylist {
  id: string;
  name?: string;
  title?: string;
  description?: string;
  thumbnailUrl?: string | null;
  cover?: { videoId?: string; thumbnailUrl?: string | null } | null;
  videosCount?: number;
  videos?: unknown[];
}

/** Content the API filled in for a section (docs/specs/CHANNEL-SECTIONS.md §8.3) */
export interface SectionContent {
  videos?: VideoObject[];
  playlist?: SectionPlaylist;
  playlists?: SectionPlaylist[];
  channels?: ChannelSummary[];
  streams?: ApiLiveStream[];
  posts?: SectionPostSummary[];
  spotlight?: { trailer?: VideoObject; returning?: VideoObject };
}

/**
 * Section as returned by GET /api/channels/{id}/sections/populated: the view
 * model plus the server-populated content. Visitors only get sections with
 * content; editors get every section with `canEdit` and an `emptyHint`.
 */
export type PopulatedChannelSection = ChannelSection & {
  content?: {
    videoIds?: string[];
    playlistId?: string;
    playlistIds?: string[];
    channelIds?: string[];
    trailerVideoId?: string;
    returningVideoId?: string;
  };
  sort?: 'latest' | 'popular';
  liveFilter?: 'live_and_upcoming' | 'past';
  postMode?: 'latest' | 'pinned';
  consented?: boolean;
  populatedContent?: SectionContent;
  isEmpty?: boolean;
  emptyHint?: SectionEmptyHint;
  canEdit?: boolean;
};

/**
 * The key of the default title: Shorts and live sections read differently
 * by their order and filter ("Popular Shorts", "Past live streams").
 */
export function sectionLabelKey(
  section: Pick<PopulatedChannelSection, 'type' | 'sort' | 'liveFilter'>
): ChannelSectionType | 'shorts_popular' | 'live_streams_past' {
  if (section.type === 'shorts' && section.sort === 'popular') return 'shorts_popular';
  if (section.type === 'live_streams' && section.liveFilter === 'past') return 'live_streams_past';
  return section.type;
}

/**
 * Title shown for a section: the owner's title, or the localized default.
 * Titles generated by older clients ("recent_uploads section") count as unset.
 */
export function resolveSectionTitle(title: string | undefined | null, fallback: string): string {
  const trimmed = (title || '').trim();
  if (!trimmed || /^[a-z_]+ section$/.test(trimmed)) {
    return fallback;
  }
  return trimmed;
}

/** Channels the API filled in for a section (featured or subscribed channels) */
export function getSectionPopulatedChannels(section: PopulatedChannelSection): ChannelSummary[] {
  return section.populatedContent?.channels ?? [];
}

/**
 * Stream status values accepted by GET /api/live-streams
 */
export type LiveStreamStatusFilter = 'scheduled' | 'live' | 'ended';

/**
 * Live stream as returned by GET /api/live-streams (API view model)
 */
export interface ApiLiveStream {
  id: string;
  title: string;
  channelId: string;
  channelName?: string;
  thumbnailUrl?: string;
  status: 'scheduled' | 'live' | 'ended' | 'cancelled';
  currentViewers?: number;
  scheduledStartTime?: string;
  actualStartTime?: string;
  actualEndTime?: string;
  duration?: number;
}

/**
 * GET /api/live-streams responds with `{ success, result: { data, cursor } }`;
 * older clients typed it as `{ success, data: { data } }`. Accept both.
 */
export function extractLiveStreams(response: unknown): ApiLiveStream[] {
  if (!response || typeof response !== 'object') return [];
  const body = response as {
    result?: { data?: ApiLiveStream[] };
    data?: { data?: ApiLiveStream[] } | ApiLiveStream[];
  };
  if (Array.isArray(body.result?.data)) return body.result.data;
  if (Array.isArray(body.data)) return body.data;
  if (body.data && Array.isArray(body.data.data)) return body.data.data;
  return [];
}

const FALLBACK_THUMBNAIL = BRAND_LOGO_LARGE;

function toDate(value?: string): Date | undefined {
  if (!value) return undefined;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? undefined : date;
}

/**
 * Map an API live stream into the card model used by LiveStreamCard
 */
export function toLiveStreamCardModel(stream: ApiLiveStream, channelName = ''): LiveStream {
  return {
    id: stream.id,
    title: stream.title,
    thumbnailUrl: stream.thumbnailUrl || FALLBACK_THUMBNAIL,
    status: stream.status === 'cancelled' ? 'ended' : stream.status,
    viewerCount: stream.currentViewers,
    channel: {
      id: stream.channelId,
      name: stream.channelName || channelName,
    },
    startedAt: toDate(stream.actualStartTime),
    scheduledStartTime: toDate(stream.scheduledStartTime),
    endedAt: toDate(stream.actualEndTime),
    duration: stream.duration,
  };
}

/**
 * The section has something to draw for its type (ChannelSectionRenderer draws nothing otherwise).
 * When no section of a channel has, its Home tab falls back to its uploads (channelHomeFallback).
 */
export function sectionHasContent(section: PopulatedChannelSection): boolean {
  const c = section.populatedContent;
  if (!c) return false;
  switch (section.type) {
    case 'channel_spotlight':
      return !!(c.spotlight?.trailer || c.spotlight?.returning);
    case 'multiple_playlists':
    case 'created_playlists':
      return !!c.playlists?.length;
    case 'featured_channels':
    case 'subscribed_channels':
      return !!c.channels?.length;
    case 'live_streams':
      return !!c.streams?.length;
    case 'community_posts':
      return !!c.posts?.length;
    default:
      return !!c.videos?.length;
  }
}

/** A channel's Home tab when it has no section to show (YouTube style, #1206): its latest uploads */
export interface ChannelHomeFallback {
  videos: VideoObject[];
  shorts: VideoObject[];
  /** Missing when the server had them too late: the client loads them */
  playlists?: SectionPlaylist[];
}

/** The fallback as sections the renderer already draws (titles, "View all" links and shelves) */
export function fallbackSections(channelId: string, fallback: ChannelHomeFallback): PopulatedChannelSection[] {
  const base = { channelId, userId: '', title: '', style: 'horizontal_row', itemCount: 12, showTimestamp: true, showChannelName: false, dateCreated: '' } as Partial<PopulatedChannelSection>;
  const sections: Array<Partial<PopulatedChannelSection>> = [];
  if (fallback.videos.length) sections.push({ ...base, id: 'fallback-videos', type: 'recent_uploads', position: 0, populatedContent: { videos: fallback.videos } });
  if (fallback.shorts.length) sections.push({ ...base, id: 'fallback-shorts', type: 'shorts', position: 1, populatedContent: { videos: fallback.shorts } });
  if (fallback.playlists?.length) sections.push({ ...base, id: 'fallback-playlists', type: 'created_playlists', position: 2, populatedContent: { playlists: fallback.playlists } });
  return sections as PopulatedChannelSection[];
}
