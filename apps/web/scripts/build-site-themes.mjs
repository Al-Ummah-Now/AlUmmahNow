// Writes every Fanous theme into one stylesheet, scoped by <html data-theme>, so
// the site theme can change without a build. Light and dark follow next-themes' class.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const THEMES = ['lantern', 'zujaj', 'nahas', 'fawanees'];
const DEFAULT = 'fawanees';
const root = (path) => fileURLToPath(new URL(path, import.meta.url));

export function buildSiteThemes() {
  const blocks = THEMES.map((id) => {
    const scope = `html[data-theme='${id}']`;
    const css = readFileSync(root(`../../../packages/fanous-tokens/generated/${id}/web/tokens.css`), 'utf8');
    return css
      .replace(/^:root \{/m, id === DEFAULT ? `:root, ${scope} {` : `${scope} {`)
      .replace(/^\[data-fanous-theme='dark'\] \{/m, id === DEFAULT ? `.dark, ${scope}.dark {` : `${scope}.dark {`)
      .replace(/^\[data-fanous-theme='light'\] \{/m, id === DEFAULT ? `html:not(.dark), ${scope}:not(.dark) {` : `${scope}:not(.dark) {`);
  });
  return `/* Generated by scripts/build-site-themes.mjs. Do not edit. */\n${blocks.join('\n')}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(root('../src/theme/site-themes.css'), buildSiteThemes());
}
