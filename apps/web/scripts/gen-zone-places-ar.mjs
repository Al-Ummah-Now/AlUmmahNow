// Writes src/lib/time/zone-places-ar.ts: each IANA zone's place in Arabic, from CLDR's generic location
// name («توقيت نيويورك» → «نيويورك»; a one-zone country by its name: «مصر»). Browsers ship trimmed ICU
// data without Arabic city names (Chromium answers «توقيت New York»), so the names come from Node's full
// ICU once and are committed. Run with Node built with full ICU: node apps/web/scripts/gen-zone-places-ar.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const at = new Date(Date.UTC(2026, 0, 15));
const out = {};
for (const zone of Intl.supportedValuesOf('timeZone')) {
  const name = new Intl.DateTimeFormat('ar', { timeZone: zone, timeZoneName: 'shortGeneric' })
    .formatToParts(at)
    .find((p) => p.type === 'timeZoneName')?.value;
  if (!name || /(GMT|UTC|غرينتش|[0-9٠-٩A-Za-z])/.test(name)) continue;
  const place = name.replace(/^توقيت\s+/, '').trim();
  if (place) out[zone] = place;
}
const body = Object.entries(out).map(([z, p]) => `  ${JSON.stringify(z)}: ${JSON.stringify(p)},`).join('\n');
const file = fileURLToPath(new URL('../src/lib/time/zone-places-ar.ts', import.meta.url));
writeFileSync(file, `// GENERATED by apps/web/scripts/gen-zone-places-ar.mjs from CLDR (Node ICU ${process.versions.icu}). Do not edit.\n// Each zone's place in Arabic: browsers' trimmed ICU has no Arabic city names.\nexport const ZONE_PLACES_AR: Readonly<Record<string, string>> = {\n${body}\n};\n`);
console.log(`${Object.keys(out).length} zones -> ${file}`);
