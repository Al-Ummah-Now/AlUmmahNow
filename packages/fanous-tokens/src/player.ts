// Player chrome tokens: themes/<theme>/player.json -> generated-player/<theme>.css.
// `player.ts` writes the CSS, `player.ts --check` fails on an invalid theme or stale output.
// The videos site now compiles player chrome from its theme packages (packages/theme-packages), which a test
// keeps equal to these files; these remain the source for the player harness and native apps.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PLAYER_TOKENS = [
  'bar', 'bar-edge', 'bar-pad', 'bar-inset', 'bar-radius', 'blur',
  'icon', 'dim',
  'track', 'track-edge', 'buffered', 'played', 'glow',
  'handle', 'handle-edge',
  'hover', 'press', 'shape',
  'tip-bg', 'tip-text', 'tip-edge',
  'menu', 'menu-edge', 'menu-hover', 'menu-selected',
  'accent',
  'big', 'big-icon', 'big-edge',
  'spin',
  'pill', 'pill-edge',
  'cue', 'err', 'scrim',
  'live', 'live-text',
] as const;

/**
 * Tokens with one value for every theme, emitted into each theme's file so the contract stays one
 * set of custom properties. `layer` is the stacking level of the player's dialogs, menus and
 * tooltips, which are portalled to the page body (or the fullscreen element): above the site header
 * (z-index 50), the consent banner (60) and Video.js's full-window player (1000).
 */
export const PLAYER_SHARED_TOKENS = { layer: '1100' } as const;

export const THEMES_DIR = fileURLToPath(new URL('../themes', import.meta.url));
export const OUT_DIR = fileURLToPath(new URL('../generated-player', import.meta.url));

export type PlayerTheme = Record<string, string>;

/** Every theme folder that has a player.json, by id. */
export function loadPlayerThemes(dir: string = THEMES_DIR): Record<string, PlayerTheme> {
  const ids = existsSync(dir) ? readdirSync(dir).filter((id) => existsSync(join(dir, id, 'player.json'))).sort() : [];
  return Object.fromEntries(ids.map((id) => [id, JSON.parse(readFileSync(join(dir, id, 'player.json'), 'utf8')).player ?? {}]));
}

/** Problems with one theme's tokens, each naming the theme and token. */
export function validatePlayerTheme(id: string, tokens: PlayerTheme): string[] {
  const errors: string[] = [];
  const known = new Set<string>(PLAYER_TOKENS);
  for (const name of PLAYER_TOKENS) {
    const value = tokens[name];
    if (typeof value !== 'string' || value.trim() === '') errors.push(`${id}: player.${name} is missing`);
    else if (/[;{}]/.test(value) || /<\/?style|url\(/i.test(value)) errors.push(`${id}: player.${name} must be a single CSS value without ; { } or url()`);
  }
  for (const name of Object.keys(tokens)) if (!known.has(name)) errors.push(`${id}: player.${name} is not a player token`);
  return errors;
}

export function playerCss(id: string, tokens: PlayerTheme): string {
  const lines = [
    ...PLAYER_TOKENS.map((name) => `  --fanous-player-${name}: ${tokens[name]};`),
    ...Object.entries(PLAYER_SHARED_TOKENS).map(([name, value]) => `  --fanous-player-${name}: ${value};`),
  ];
  return `/* Generated by @al-ummah/fanous-tokens from themes/${id}/player.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
}

export function generatePlayer(themes: Record<string, PlayerTheme>): { files: Record<string, string>; errors: string[] } {
  const errors = Object.entries(themes).flatMap(([id, t]) => validatePlayerTheme(id, t));
  if (!themes.lantern) errors.push('lantern: themes/lantern/player.json is required (the default theme)');
  const files = Object.fromEntries(Object.entries(themes).map(([id, t]) => [`${id}.css`, playerCss(id, t)]));
  return { files, errors };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { files, errors } = generatePlayer(loadPlayerThemes());
  for (const e of errors) console.error(`PLAYER TOKEN ${e}`);
  if (errors.length) process.exit(1);
  if (process.argv.includes('--check')) {
    const onDisk = existsSync(OUT_DIR) ? readdirSync(OUT_DIR) : [];
    const stale = [
      ...Object.entries(files).filter(([p, c]) => !existsSync(join(OUT_DIR, p)) || readFileSync(join(OUT_DIR, p), 'utf8') !== c).map(([p]) => p),
      ...onDisk.filter((p) => !(p in files)),
    ];
    if (stale.length) {
      console.error(`Player tokens are stale, run pnpm tokens:generate:\n  ${stale.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`Player tokens: ${Object.keys(files).length} themes valid and current.`);
  } else {
    rmSync(OUT_DIR, { recursive: true, force: true });
    mkdirSync(OUT_DIR, { recursive: true });
    for (const [p, c] of Object.entries(files)) writeFileSync(join(OUT_DIR, p), c);
    console.log(`Wrote ${Object.keys(files).length} player token files to generated-player/.`);
  }
}
