const cssColor = (c: Rgba) => (c[3] === 1 ? `#${hex6(c).toLowerCase()}` : `rgba(${c.slice(0, 3).map((v) => Math.round(v)).join(',')},${alpha(c)})`);
const cssStops = (stops: Stop[]) => stops.map((s) => `${cssColor(s.color)} ${num(s.at * 100)}%`).join(', ');

/** GTK CSS for one fill layer. `rtl` picks the mirrored form of a logical layer. */
export function gtkFill(f: Fill, rtl: boolean): string {
  if (f.kind === 'solid') return `linear-gradient(${cssColor(f.color)}, ${cssColor(f.color)})`;
  if (f.kind === 'linear') {
    const angle = f.logical && rtl ? (360 - f.angle) % 360 : f.angle;
    return `linear-gradient(${num(angle)}deg, ${cssStops(f.stops)})`;
  }
  const cx = f.logicalX && rtl ? 1 - f.cx : f.cx;
  const size = typeof f.size === 'string' ? f.size : `${num(f.size.rx * 100)}% ${num(f.size.ry * 100)}%`;
  return `radial-gradient(${f.shape} ${size} at ${num(cx * 100)}% ${num(f.cy * 100)}%, ${cssStops(f.stops)})`;
}
const gtkShadows = (list: Shadow[]) => (list.length ? list.map((s) => `${s.inset ? 'inset ' : ''}${num(s.x)}px ${num(s.y)}px ${num(s.blur)}px ${num(s.spread)}px ${cssColor(s.color)}`).join(', ') : 'none');
const gtkBg = (list: Fill[], rtl = false) => list.map((f) => gtkFill(f, rtl)).join(', ');
const hasLogical = (list: Fill[]) => list.some((f) => (f.kind === 'linear' && f.logical) || (f.kind === 'radial' && f.logicalX));

