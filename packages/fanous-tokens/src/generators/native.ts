// ---------- assets ----------

function assets(reg: NativeRegistry): Record<string, string> {
  const out: Record<string, string> = {};
  for (const t of reg.themes) {
    for (const m of MODES) {
      for (const [name, svg] of Object.entries(t.svg[m])) {
        out[`native/svg/${t.id}/${m}/${name}.svg`] = `${svg}\n`;
        const vd = svgToVector(svg, `${t.id} ${m} ${name}`);
        // Android resource names are lowercase with underscores. The mode is in the name, not a -night folder,
        // because the app's light or dark setting can differ from the system's.
        out[`native/android/drawable/fanous_${t.id}_${name.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase()}_${m}.xml`] = vd;
      }
    }
  }
  return out;
}

export function generateNative(reg: NativeRegistry, base: Model): Record<string, string> {
  const files: Record<string, string> = {
    'native/swift/FanousThemes.swift': swift(reg, base),
    'native/kotlin/net/alummahnow/fanous/FanousThemes.kt': kotlin(reg, base),
    'native/csharp/FanousThemes.cs': csharp(reg, base),
    'native/registry.json': `${JSON.stringify({ $comment: HEADER, ids: reg.ids, fallback: reg.fallback }, null, 2)}\n`,
    ...assets(reg),
  };
  for (const t of reg.themes) for (const m of MODES) files[`native/gtk/${t.id}${m === 'dark' ? '-dark' : ''}.css`] = gtk(t, m);
  return files;
}
