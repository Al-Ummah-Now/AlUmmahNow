const HEADER_NATIVE = 'Generated by @al-ummah/fanous-tokens (native registry). Do not edit.';
const num = (n: number) => (Number.isInteger(n) ? String(n) : String(Math.round(n * 10000) / 10000));
const hex6 = ([r, g, b]: Rgba) => [r, g, b].map((c) => Math.round(c).toString(16).padStart(2, '0')).join('').toUpperCase();
const alpha = (c: Rgba) => num(Math.round(c[3] * 1000) / 1000);

interface Lang {
  rgba(c: Rgba): string;
  stop(s: Stop): string;
  list(items: string[], indent: string): string;
  fill(f: Fill, indent: string): string;
  shadow(s: Shadow): string;
}

function fills(lang: Lang, list: Fill[], indent: string) { return lang.list(list.map((f) => lang.fill(f, indent + '    ')), indent); }
function shadows(lang: Lang, list: Shadow[], indent: string) { return lang.list(list.map((s) => lang.shadow(s)), indent); }

