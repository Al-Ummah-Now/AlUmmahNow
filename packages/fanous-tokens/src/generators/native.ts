const swiftLang: Lang = {
  rgba: (c) => (c[3] === 1 ? `.init(0x${hex6(c)})` : `.init(0x${hex6(c)}, ${alpha(c)})`),
  stop: (s) => `.init(${swiftLang.rgba(s.color)}, ${num(s.at)})`,
  list: (items, indent) => (items.length === 0 ? '[]' : items.join('').length < 90 ? `[${items.join(', ')}]` : `[\n${items.map((i) => `${indent}    ${i}`).join(',\n')},\n${indent}]`),
  fill: (f, indent) => {
    const stops = swiftLang.list(f.kind === 'solid' ? [] : f.stops.map(swiftLang.stop), indent);
    if (f.kind === 'solid') return `.solid(${swiftLang.rgba(f.color)})`;
    if (f.kind === 'linear') return `.linear(angle: ${num(f.angle)}, logical: ${f.logical}, stops: ${stops})`;
    const extent = typeof f.size === 'string' ? `.${camel(f.size)}` : `.radii(${num(f.size.rx)}, ${num(f.size.ry)})`;
    return `.radial(circle: ${f.shape === 'circle'}, extent: ${extent}, center: .init(${num(f.cx)}, ${num(f.cy)}), logicalX: ${f.logicalX}, stops: ${stops})`;
  },
  shadow: (s) => `.init(inset: ${s.inset}, x: ${num(s.x)}, y: ${num(s.y)}, blur: ${num(s.blur)}, spread: ${num(s.spread)}, color: ${swiftLang.rgba(s.color)})`,
};

