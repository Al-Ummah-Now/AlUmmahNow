/**
 * Subtitle/Caption-related types
 * These types are shared between frontend and backend
 */

/**
 * Subtitle track metadata
 */
export interface SubtitleTrack {
  id: string; // UUID
  language: string; // ISO 639-1 code (en, ar, ur, etc.)
  label: string; // Display name ("English", "العربية")
  kind: 'subtitles' | 'captions'; // subtitles vs closed captions
  isDefault?: boolean; // Default track to show
  isAutoGenerated?: boolean; // AI-generated flag
  uploadedBy: string; // User ID who uploaded
  uploadedAt: string; // ISO timestamp
  fileSize: number; // Size in bytes
  format: 'vtt' | 'srt' | 'sbv'; // Original format
  url: string; // CDN URL to WebVTT file
  status: 'processing' | 'ready' | 'error';
  error?: string; // Error message if failed
}

/**
 * Subtitle metadata for a video
 */
export interface SubtitleMetadata {
  videoId: string;
  tracks: SubtitleTrack[];
  dateCreated: string;
  dateModified: string;
}

/**
 * A single subtitle cue (caption entry)
 */
export interface SubtitleCue {
  id?: string;
  startTime: number; // seconds
  endTime: number; // seconds
  text: string;
  position?: { x: number; y: number };
  align?: 'start' | 'middle' | 'end';
  line?: number;
  size?: number;
}

/**
 * Parsed subtitle data
 */
export interface SubtitleData {
  cues: SubtitleCue[];
  metadata?: Record<string, string>;
}

/**
 * Validation error for subtitle content
 */
export interface ValidationError {
  type: 'timing' | 'content' | 'format';
  message: string;
  cueIndex?: number;
  line?: number;
}

/**
 * Validation result
 */
export interface ValidationResult {
  valid: boolean;
  errors: ValidationError[];
  warnings?: ValidationError[];
}

/**
 * Request to upload a subtitle track
 */
export interface SubtitleUploadRequest {
  language: string; // ISO 639-1 code
  label?: string; // Display name (optional, auto-detected if not provided)
  file: File | string; // File object or file content
  isDefault?: boolean; // Set as default track
  kind?: 'subtitles' | 'captions'; // Default: 'subtitles'
}

/**
 * Request to update a subtitle track
 */
export interface SubtitleUpdateRequest {
  cues?: SubtitleCue[]; // Updated cues
  label?: string; // Update display name
  isDefault?: boolean; // Update default status
}

/**
 * Response for subtitle upload
 */
export interface SubtitleUploadResponse {
  success: boolean;
  data?: {
    track: SubtitleTrack;
    video?: any; // Updated VideoObject
  };
  error?: string;
}

/**
 * Response for listing subtitles
 */
export interface SubtitleListResponse {
  success: boolean;
  data?: {
    tracks: SubtitleTrack[];
    defaultLanguage?: string;
  };
  error?: string;
}

/**
 * Supported subtitle languages
 */
export interface SubtitleLanguage {
  code: string; // ISO 639-1
  label: string; // Display name
  dir: 'ltr' | 'rtl'; // Text direction
}

