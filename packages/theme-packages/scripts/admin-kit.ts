// Copies what the admin theme builder needs into apps/admin-web/public/theme-kit/ (generated, not
// committed): the built-in packages (to duplicate and preview), and the videos site's own component
// stylesheets and fonts, so the builder's preview renders real components rather than a mock.
//
//   theme-kit/builtins/index.json                    [{ id, name, files: [...] }]
//   theme-kit/builtins/<id>/theme.json, assets/...
//   theme-kit/site.css                                font faces + system.css + pages.css from apps/web
//   theme-kit/fonts/*.woff2
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUILT_IN, THEMES_DIR, loadPackageDir } from './load.ts';

const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const WEB = join(ROOT, 'apps/web');
const OUT = join(ROOT, 'apps/admin-web/public/theme-kit');

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'builtins'), { recursive: true });
mkdirSync(join(OUT, 'fonts'), { recursive: true });

const index = BUILT_IN.ids.map((id) => {
  const { theme, assets } = loadPackageDir(join(THEMES_DIR, id));
  cpSync(join(THEMES_DIR, id), join(OUT, 'builtins', id), { recursive: true });
  return { id, name: theme.name, version: theme.version, files: Object.keys(assets).sort() };
});
writeFileSync(join(OUT, 'builtins/index.json'), JSON.stringify({ default: BUILT_IN.default, themes: index }));

const faces = readFileSync(join(WEB, 'src/theme/font-faces.css'), 'utf8');
for (const font of new Set(faces.match(/\/fonts\/[a-z0-9-]+\.woff2/g) ?? [])) {
  const src = join(WEB, 'public', font);
  if (existsSync(src)) cpSync(src, join(OUT, font.replace('/fonts/', 'fonts/')));
}
const css = [
  faces.replaceAll("url('/fonts/", "url('/theme-kit/fonts/"),
  readFileSync(join(WEB, 'src/theme/system.css'), 'utf8'),
  readFileSync(join(WEB, 'src/theme/pages.css'), 'utf8'),
].join('\n');
writeFileSync(join(OUT, 'site.css'), `/* Generated by packages/theme-packages/scripts/admin-kit.ts from apps/web/src/theme. Do not edit. */\n${css}`);
console.log(`Theme kit: ${index.length} built-in packages and the site's component CSS in apps/admin-web/public/theme-kit.`);
