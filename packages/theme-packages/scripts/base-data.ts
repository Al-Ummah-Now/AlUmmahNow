// The platform-wide data every package compiles against, read from @al-ummah/fanous-tokens:
// colour roles and their contrast rules, component colour parts, and the shared scales
// (type, spacing, motion, focus, TV, layout) that stay the same in every theme.
import { readFileSync } from 'node:fs';
import { buildModel } from '../../fanous-tokens/src/model.ts';
import { composeTokens, loadThemes, loadTokens, resolveTheme } from '../../fanous-tokens/src/themes.ts';

export function baseData() {
  const tokens = loadTokens();
  const roleTree = JSON.parse(readFileSync(new URL('../../fanous-tokens/tokens/fanous.tokens.json', import.meta.url), 'utf8')).color.roles;
  const roles = Object.entries<any>(roleTree).filter(([k]) => !k.startsWith('$')).map(([name, t]) => ({ name, role: t.$extensions.fanous.role as string, ...(t.$extensions.fanous.on ? { on: t.$extensions.fanous.on as string } : {}) }));
  const components = JSON.parse(readFileSync(new URL('../../fanous-tokens/tokens/components.json', import.meta.url), 'utf8'));
  const themes = loadThemes();
  const model = buildModel(composeTokens(tokens, resolveTheme(themes.defaultTheme, themes)));
  return {
    roles,
    parts: Object.entries<string>(components.parts).map(([part, role]) => ({ part, role })),
    componentPairs: components.pairs as [string, string, number][],
    fontPairs: model.fontPairs,
    typography: model.typography,
    spacing: model.spacing.map(({ name, value }) => ({ name, value })),
    duration: model.duration.map(({ name, value }) => ({ name, value })),
    easing: model.easing.map(({ name, value }) => ({ name, value })),
    focus: model.focus.map(({ name, value }) => ({ name, value })),
    tv: model.tv.map(({ name, value }) => ({ name, value })),
    layout: model.layout.map(({ name, value }) => ({ name, value })),
  };
}

export const baseModule = () => `// Generated by packages/theme-packages/scripts/build-themes.ts from @al-ummah/fanous-tokens. Do not edit.
export const BASE = ${JSON.stringify(baseData(), null, 2)} as const;
export type Base = typeof BASE;
`;
