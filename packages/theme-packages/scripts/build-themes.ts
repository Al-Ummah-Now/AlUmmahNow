// Builds the built-in theme packages into the stylesheets the videos site imports, and regenerates
// the package library's data modules. `--check` fails when a package is invalid or any output is stale.
//
//   themes/<id>/theme.json + assets/   ->  apps/web/src/theme/site-themes.css   (design tokens)
//                                          apps/web/src/theme/materials.css     (materials per component)
//                                          apps/web/src/theme/fonts.css         (body fonts)
//                                          apps/web/src/theme/player-themes.css (player chrome)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { baseModule } from './base-data.ts';

const PKG = fileURLToPath(new URL('..', import.meta.url));
const ROOT = join(PKG, '../..');
const WEB_THEME = join(ROOT, 'apps/web/src/theme');
const check = process.argv.includes('--check');

const outputs: Record<string, string> = {};
const schema = readFileSync(join(ROOT, 'docs/themes/theme-package.v1.schema.json'), 'utf8');
outputs[join(PKG, 'src/schema.generated.ts')] = `// Generated by scripts/build-themes.ts from docs/themes/theme-package.v1.schema.json. Do not edit.\nexport const SCHEMA: Record<string, any> = ${schema.trim()};\n`;
outputs[join(PKG, 'src/base.generated.ts')] = baseModule();

// Data modules first: the compiler imports them.
const stale: string[] = [];
for (const [file, content] of Object.entries(outputs)) {
  if (check) { if (!existsSync(file) || readFileSync(file, 'utf8') !== content) stale.push(file); }
  else writeFileSync(file, content);
}

const { loadPackageDir, BUILT_IN } = await import('./load.ts');
const { validatePackage } = await import('../src/validate.ts');
const { compilePackage } = await import('../src/compile.ts');

const errors: string[] = [];
const compiled = BUILT_IN.ids.map((id: string) => {
  const files = loadPackageDir(join(PKG, 'themes', id));
  if (files.theme.id !== id) errors.push(`${id}: theme.json id is "${files.theme.id}"`);
  const result = validatePackage(files.theme, { assets: files.assets, builtIn: true });
  for (const e of result.errors) errors.push(`${id}: ${e.path}: ${e.message}`);
  if (result.errors.length) return undefined;
  return compilePackage(files.theme, { isDefault: id === BUILT_IN.default, rootFallback: true });
});
if (errors.length) {
  for (const e of errors) console.error(`THEME PACKAGE ${e}`);
  process.exit(1);
}

const builtins = BUILT_IN.ids.map((id: string) => {
  const t = loadPackageDir(join(PKG, 'themes', id)).theme;
  return { id, version: t.version, kind: t.kind, name: t.name };
});
const builtinsModule = `// Generated by scripts/build-themes.ts from themes/index.json. Do not edit.
export const BUILT_IN_THEMES = ${JSON.stringify(builtins, null, 2)} as const;
export const DEFAULT_THEME = ${JSON.stringify(BUILT_IN.default)};
export const BUILT_IN_IDS: readonly string[] = BUILT_IN_THEMES.map((t) => t.id);
`;
const builtinsFile = join(PKG, 'src/builtins.generated.ts');
if (check) { if (!existsSync(builtinsFile) || readFileSync(builtinsFile, 'utf8') !== builtinsModule) stale.push(builtinsFile); }
else writeFileSync(builtinsFile, builtinsModule);

const all = compiled as NonNullable<(typeof compiled)[number]>[];
const header = (what: string) => `/* Generated by packages/theme-packages/scripts/build-themes.ts from the built-in theme packages (${what}). Do not edit. */\n`;
const web: Record<string, string> = {
  [join(WEB_THEME, 'site-themes.css')]: header('design tokens') + all.map((c) => c.tokens).join('\n'),
  [join(WEB_THEME, 'materials.css')]: header('materials') + all.map((c) => c.materials).join(''),
  [join(WEB_THEME, 'fonts.css')]: header('body fonts') + all.map((c) => c.fonts).join(''),
  [join(WEB_THEME, 'player-themes.css')]: header('player chrome') + all.map((c) => c.player).join(''),
};
for (const [file, content] of Object.entries(web)) {
  if (check) { if (!existsSync(file) || readFileSync(file, 'utf8') !== content) stale.push(file); }
  else writeFileSync(file, content);
}

if (check) {
  if (stale.length) {
    console.error(`Theme package outputs are stale. Run pnpm themes:build:\n  ${stale.map((f) => relative(ROOT, f)).join('\n  ')}`);
    process.exit(1);
  }
  console.log(`Theme packages: ${BUILT_IN.ids.length} built-in packages valid, outputs current.`);
} else {
  console.log(`Built ${BUILT_IN.ids.length} theme packages into ${relative(ROOT, WEB_THEME)}.`);
}

